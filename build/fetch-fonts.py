#!/usr/bin/env python3
"""Download the three webfonts and write a self-hosted @font-face sheet.

The site used to pull these from fonts.googleapis.com on every page. Self-hosting
means one less DNS lookup and TLS handshake in the critical path, no third-party
request for the privacy notice to explain, and files LiteSpeed can cache and
preload. Run once; re-run only to add a weight.

    python3 build/fetch-fonts.py
"""
import re, subprocess, pathlib, sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT  = ROOT / 'assets' / 'fonts'
# a modern UA, or Google serves the far larger .ttf fallback
UA = ('Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) '
      'Chrome/120.0.0.0 Safari/537.36')
URL = ('https://fonts.googleapis.com/css2'
       '?family=Anton'
       '&family=Space+Grotesk:wght@500;600;700'
       '&family=Inter:wght@400;500;600;700;800'
       '&display=swap')
# latin is all this site needs; latin-ext carries the odd accented client name
KEEP = ('latin', 'latin-ext')


def curl(url, binary=False):
    r = subprocess.run(['curl', '-sS', '-A', UA, url], capture_output=True)
    if r.returncode:
        sys.exit('curl failed for %s: %s' % (url, r.stderr.decode()[:200]))
    return r.stdout if binary else r.stdout.decode()


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    css = curl(URL)
    # google's css2 output is one commented subset name per @font-face block
    blocks = re.findall(r'(/\*\s*([\w-]+)\s*\*/\s*@font-face\s*\{.*?\})', css, re.S)
    kept, seen = [], {}
    for block, subset in blocks:
        if subset not in KEEP:
            continue
        fam = re.search(r"font-family:\s*'([^']+)'", block).group(1)
        wt  = re.search(r'font-weight:\s*(\d+)', block).group(1)
        src = re.search(r'url\((https://fonts\.gstatic\.com/[^)]+)\)', block).group(1)
        name = '%s-%s-%s.woff2' % (fam.lower().replace(' ', '-'), wt, subset)
        if name not in seen:
            (OUT / name).write_bytes(curl(src, binary=True))
            seen[name] = True
        kept.append(re.sub(r'url\(https://[^)]+\)', "url('fonts/%s')" % name, block))
    sheet = ('/* Self-hosted webfaces. Generated by build/fetch-fonts.py — do not\n'
             '   edit by hand. Paths are relative to the stylesheet that imports it. */\n'
             + '\n'.join(b.strip() for b in kept) + '\n')
    (ROOT / 'assets' / 'fonts.css').write_text(sheet)
    total = sum(f.stat().st_size for f in OUT.glob('*.woff2'))
    print('%d faces, %d files, %.0f KB -> assets/fonts.css' % (len(kept), len(seen), total / 1024))


if __name__ == '__main__':
    main()
