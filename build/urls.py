#!/usr/bin/env python3
"""Build the address ledger: every URL the live site answers on today.

The rebuild swaps the server, the theme and every page, but the addresses have
to survive exactly — that is where the search ranking lives. So the 116 live
URLs captured in the site audit become a checklist, and every one of them ends
up either BUILT at the same address or explicitly REDIRECTED somewhere. Nothing
is allowed to just disappear.

    python3 build/urls.py

Reads the audit on the claude/site-audit branch (no network needed) and writes
seo/urls.json and seo/URLS.md. Re-run after adding a page to build/build.py.
"""
import json, re, subprocess, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
AUDIT = 'origin/claude/site-audit:site-audit/INDEX.md'


def audit_index():
    r = subprocess.run(['git', 'show', AUDIT], cwd=ROOT, capture_output=True, text=True)
    if r.returncode:
        sys.exit('cannot read %s — fetch the audit branch first:\n'
                 '  git fetch origin claude/site-audit' % AUDIT)
    return r.stdout


def parse(md):
    """Section 1 of the audit is one markdown table per group of pages."""
    body = md[md.index('## 1. Every URL found'):md.index('## 2.')]
    rows, group = [], ''
    for line in body.splitlines():
        if line.startswith('### '):
            group = line[4:].strip()
        m = re.match(r'\|\s*`([^`]+)`\s*\|\s*(.*?)\s*\|', line)
        if m:
            rows.append({'slug': m.group(1), 'title': m.group(2), 'group': group})
    return rows


def built_slugs():
    """Whatever build.py currently produces, read straight off the source."""
    src = (ROOT / 'build' / 'build.py').read_text()
    block = src[src.index('PAGES = ['):src.index(']\n', src.index('PAGES = ['))]
    return {'/' + s + '/' if s else '/' for s in re.findall(r"'slug':\s*'([^']*)'", block)}


def main():
    rows = parse(audit_index())
    built = built_slugs()
    for r in rows:
        r['status'] = 'built' if r['slug'] in built else 'todo'

    out = ROOT / 'seo'
    out.mkdir(exist_ok=True)
    (out / 'urls.json').write_text(json.dumps(
        {'source': 'site audit, 2026-08-23, 116 live URLs',
         'rule': 'every slug below must resolve on the new site at the same address, '
                 'or carry a 301 to a named replacement',
         'urls': rows}, indent=2) + '\n')

    done = sum(1 for r in rows if r['status'] == 'built')
    lines = ['# Address ledger',
             '',
             'Generated by `build/urls.py` — do not edit by hand.',
             '',
             'Every address the live site answers on today. The new site has to answer on',
             'all of them, at the same address, or 301 to a named replacement. This is the',
             'only thing standing between the rebuild and losing twenty years of ranking.',
             '',
             '**%d of %d built.**' % (done, len(rows)),
             '']
    group = None
    for r in rows:
        if r['group'] != group:
            group = r['group']
            lines += ['', '## %s' % group, '', '| | Address | Title |', '| --- | --- | --- |']
        lines.append('| %s | `%s` | %s |' % ('✅' if r['status'] == 'built' else '☐',
                                             r['slug'], r['title']))
    (out / 'URLS.md').write_text('\n'.join(lines) + '\n')
    print('seo/urls.json + seo/URLS.md — %d addresses, %d built' % (len(rows), done))


if __name__ == '__main__':
    main()
